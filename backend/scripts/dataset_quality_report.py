"""Dataset quality report, computed from the files (nothing typed in by hand).

    python scripts/dataset_quality_report.py [--before path/to/old_repair_records.jsonl]

Writes data/processed/quality_report.json and docs/DATASET_QUALITY_REPORT.md.
"""
import argparse, json, os, re, sys
from collections import Counter, defaultdict
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from _paths import PROCESSED, RAW
from app.datasets.importers import manufacturer_docs
from app.datasets.pipeline import content_key, validate
from app.datasets.schema import CATEGORIES

DOCS = PROCESSED.parent.parent / 'docs' / 'DATASET_QUALITY_REPORT.md'
CODE_OK = re.compile(r'^[A-Z0-9]{1,8}$')
PRIMARY = ['washing_machine', 'split_ac', 'refrigerator', 'ceiling_fan', 'microwave_oven', 'water_purifier']


def main():
    p = argparse.ArgumentParser(); p.add_argument('--before'); a = p.parse_args()
    rows = [json.loads(l) for l in (PROCESSED / 'repair_records.jsonl').read_text().splitlines() if l.strip()]
    recs, rejected_now = validate(rows)
    before_ids = {json.loads(l)['record_id'] for l in open(a.before) if l.strip()} if a.before else None
    mfr_cands, mfr_skipped = manufacturer_docs.load(RAW / 'manufacturer_docs')
    _, mfr_rejected = validate(mfr_cands)

    ids = Counter(r.record_id for r in recs)
    keys = Counter(content_key(r) for r in recs)
    by_code = defaultdict(list)
    for r in recs:
        if r.error_code:
            by_code[(r.appliance_category, (r.appliance_brand or '').lower(), (r.market or '').lower(), (r.appliance_model or '').lower(), r.error_code)].append(r)
    conflicts = [{'key': list(k), 'records': [x.record_id for x in v]} for k, v in by_code.items()
                 if len({' | '.join(sorted(f.lower() for f in x.possible_faults)) for x in v}) > 1]
    rep = {
        'existing_record_count': len(before_ids) if before_ids is not None else None,
        'new_record_count': len([r for r in recs if before_ids is not None and r.record_id not in before_ids]) if before_ids is not None else None,
        'removed_record_count': len(before_ids - set(ids)) if before_ids is not None else None,
        'final_verified_record_count': len(recs),
        'by_category': {c: n for c, n in Counter(r.appliance_category for r in recs).most_common()},
        'by_category_and_source': {f'{c} | {s}': n for (c, s), n in Counter((r.appliance_category, r.record_id.split(':')[0]) for r in recs).most_common()},
        'by_verification_status': dict(Counter(r.verification_status for r in recs)),
        'with_source_url': sum(1 for r in recs if r.source_url),
        'without_source_url': [r.record_id for r in recs if not r.source_url],
        'duplicate_record_ids': [k for k, n in ids.items() if n > 1],
        'duplicate_content': sum(n - 1 for n in keys.values() if n > 1),
        'invalid_category': [r.record_id for r in recs if r.appliance_category not in CATEGORIES],
        'unsupported_error_code_format': [r.record_id for r in recs if r.error_code and not CODE_OK.match(r.error_code)],
        'empty_diagnostic_procedure': sum(1 for r in recs if not r.diagnostic_procedure),
        'no_fault_and_no_procedure': [r.record_id for r in recs if not r.possible_faults and not r.diagnostic_procedure],
        'same_code_different_faults': conflicts,
        'rejected_in_processed_file': len(rejected_now),
        'manufacturer_docs': {'candidates': len(mfr_cands), 'skipped': len(mfr_skipped), 'rejected': len(mfr_rejected),
                              'by_evidence_level': dict(Counter(c['provenance']['evidence_level'] for c in mfr_cands)),
                              'sources': len(json.loads((RAW / 'manufacturer_docs' / 'sources.json').read_text())['sources'])},
    }
    (PROCESSED / 'quality_report.json').write_text(json.dumps(rep, indent=1))

    L = ['# Dataset quality report', '', 'Generated by `backend/scripts/dataset_quality_report.py` from `data/processed/repair_records.jsonl`. Every number below is computed from the files.', '']
    if before_ids is not None:
        L += [f"- Records before this update: **{rep['existing_record_count']}**", f"- New records added: **{rep['new_record_count']}**",
              f"- Records removed: **{rep['removed_record_count']}**"]
    L += [f"- Final valid records: **{rep['final_verified_record_count']}**", f"- Records with a source URL: **{rep['with_source_url']}**",
          f"- Records without a source URL: **{len(rep['without_source_url'])}** (FixSaathi team-written guidance, attributed to the team in provenance)",
          f"- Duplicate record ids: **{len(rep['duplicate_record_ids'])}**; duplicate content: **{rep['duplicate_content']}**",
          f"- Invalid categories: **{len(rep['invalid_category'])}**; badly formatted error codes: **{len(rep['unsupported_error_code_format'])}**",
          f"- Records with no fault and no diagnostic procedure: **{len(rep['no_fault_and_no_procedure'])}**",
          f"- Records with an empty diagnostic procedure (they still state faults or a code meaning): **{rep['empty_diagnostic_procedure']}**",
          f"- Same brand and code with different stated faults: **{len(conflicts)}**",
          f"- Manufacturer-doc candidates: {rep['manufacturer_docs']['candidates']}, rejected: {rep['manufacturer_docs']['rejected']}, skipped: {rep['manufacturer_docs']['skipped']}, from {rep['manufacturer_docs']['sources']} sources",
          '', '## By appliance', '', '| Appliance | Records |', '|---|---|']
    L += [f'| {c} | {n} |' for c, n in rep['by_category'].items()]
    L += ['', '## By appliance and origin', '', '| Appliance | Origin | Records |', '|---|---|---|']
    origin = {'appliancedb': 'ApplianceDB free sample (ODbL)', 'fixsaathi': 'FixSaathi team guidance', 'mfr': 'Manufacturer documentation (summarised)'}
    L += [f"| {k.split(' | ')[0]} | {origin.get(k.split(' | ')[1], k.split(' | ')[1])} | {n} |" for k, n in rep['by_category_and_source'].items()]
    L += ['', '## By verification status', '', '| Status | Records |', '|---|---|'] + [f'| {k} | {v} |' for k, v in rep['by_verification_status'].items()]
    L += ['', '## Manufacturer-doc evidence levels', '', '| Evidence level | Records |', '|---|---|'] + [f'| {k} | {v} |' for k, v in rep['manufacturer_docs']['by_evidence_level'].items()]
    if conflicts:
        L += ['', '## Same code, different stated faults', '', 'Kept on purpose when they come from different sources; retrieval shows both with their sources.', '']
        L += [f"- {' / '.join(x for x in c['key'] if x)}: {', '.join(c['records'])}" for c in conflicts]
    L += ['', '## Limitations', '',
          '- Washing machines still dominate because the ApplianceDB sample is mostly washers. We kept all of them rather than delete useful records.',
          '- Microwave and water-purifier records come from a small number of brands (Samsung; Kent and Aquaguard). Other brands fall back to brand-less guidance only.',
          '- Manuals hosted by retailers or manual archives are marked `unverified`: the text is the manufacturer\'s, but we could not confirm the copy.',
          '- No record has been reviewed by a field technician for this release, so none is `technician_reviewed`.',
          '- Retrieval quality has not been measured against a labelled test set; the tests check category isolation and that the expected record is returned.']
    DOCS.write_text('\n'.join(L) + '\n')
    print(json.dumps({k: v for k, v in rep.items() if k not in ('by_category_and_source', 'without_source_url')}, indent=1))


if __name__ == '__main__':
    main()
